// P3 · Compile FileRegistryV2.sol; v1 is recompiled too, to emit the frozen ABI used for
// read-only access and migration.
// Outputs:
//   contracts/out/FileRegistryV2.json        v2 full artifact (bytecode + abi)
//   contracts/out/FileRegistry.json          v1 full artifact (kept, identical to the P2 output)
//   frontend/src/lib/registry-abi.ts         v2 ABI (frontend default)
//   frontend/src/lib/registry-abi-v1.ts      v1 ABI (frozen: decoding v1 entries + migration
//                                            reads; Entry has no feePaid field, so it is
//                                            not interchangeable with the v2 ABI)
// Usage: npm run compile

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import solc from 'solc'

const ROOT = new URL('../../', import.meta.url).pathname
const OUT = ROOT + 'contracts/out/'

function compile(name) {
  const input = {
    language: 'Solidity',
    sources: { [name]: { content: readFileSync(ROOT + 'contracts/' + name, 'utf8') } },
    settings: {
      optimizer: { enabled: true, runs: 200 },
      evmVersion: 'paris', // no reliance on newer EVM opcodes, safe on any frontier domain (same as P2)
      // immutableReferences: immutables in deployedBytecode are zero placeholders, filled
      // with real values only at construction (v2's treasury). On-chain code comparison
      // must apply this patch first.
      outputSelection: {
        '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'evm.deployedBytecode.immutableReferences'] },
      },
    },
  }
  const output = JSON.parse(solc.compile(JSON.stringify(input)))
  for (const err of output.errors ?? []) {
    if (err.severity === 'error') {
      console.error(err.formattedMessage)
      process.exitCode = 1
    } else {
      console.warn(err.formattedMessage)
    }
  }
  if (process.exitCode) process.exit(process.exitCode)
  return output.contracts[name][name.replace('.sol', '')]
}

function artifact(name, contract) {
  return {
    contractName: name,
    abi: contract.abi,
    bytecode: '0x' + contract.evm.bytecode.object,
    deployedBytecode: '0x' + contract.evm.deployedBytecode.object,
    immutableReferences: contract.evm.deployedBytecode.immutableReferences ?? {},
  }
}

function emitAbi(path, constName, comment, abi) {
  writeFileSync(path, comment + `\n\nexport const ${constName} = ` + JSON.stringify(abi, null, 2) + ' as const\n')
}

mkdirSync(OUT, { recursive: true })

const v2 = compile('FileRegistryV2.sol')
const v2Artifact = artifact('FileRegistryV2', v2)
writeFileSync(OUT + 'FileRegistryV2.json', JSON.stringify(v2Artifact, null, 2))
emitAbi(
  ROOT + 'frontend/src/lib/registry-abi.ts',
  'REGISTRY_ABI',
  '// Generated by scripts/p3/compile.mjs (contracts/FileRegistryV2.sol) — do not edit by hand',
  v2.abi,
)
console.log(`v2 bytecode ${(v2Artifact.bytecode.length / 2 / 1024).toFixed(2)} KiB → ${OUT}FileRegistryV2.json`)
console.log(`v2 abi (${v2.abi.length} items) → frontend/src/lib/registry-abi.ts`)

const v1 = compile('FileRegistry.sol')
const v1Artifact = artifact('FileRegistry', v1)
writeFileSync(OUT + 'FileRegistry.json', JSON.stringify(v1Artifact, null, 2))
emitAbi(
  ROOT + 'frontend/src/lib/registry-abi-v1.ts',
  'REGISTRY_V1_ABI',
  '// Generated by scripts/p3/compile.mjs (contracts/FileRegistry.sol, frozen v1 ABI) — do not edit by hand.\n// Only for reading the legacy v1 registry (Entry has no feePaid, not interchangeable with the v2 ABI) and for the v1→v2 migration',
  v1.abi,
)
console.log(`v1 bytecode ${(v1Artifact.bytecode.length / 2 / 1024).toFixed(2)} KiB → ${OUT}FileRegistry.json`)
console.log(`v1 abi (${v1.abi.length} items) → frontend/src/lib/registry-abi-v1.ts`)
