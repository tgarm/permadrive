// P3/P4 contract compilation (table-driven). Outputs: contracts/out/<Contract>.json
// artifacts + frontend/src/lib/<name>-abi.ts frozen ABIs. Add a row per new contract.
// Usage: npm run compile

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import solc from 'solc'

const ROOT = new URL('../../', import.meta.url).pathname
const OUT = ROOT + 'contracts/out/'

// immutable slots in the artifact are zero placeholders (filled at construction) —
// the on-chain code comparison must patch them via immutableReferences first
// (patchImmutables / patchImmutablesMulti in scripts/p3/lib/chain.mjs)
function compile(name) {
  const input = {
    language: 'Solidity',
    sources: { [name]: { content: readFileSync(ROOT + 'contracts/' + name, 'utf8') } },
    settings: {
      optimizer: { enabled: true, runs: 200 },
      evmVersion: 'paris', // no reliance on newer EVM opcodes — safe on any frontier domain
      outputSelection: {
        '*': { '': ['ast'], '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'evm.deployedBytecode.immutableReferences'] },
      },
    },
  }
  const output = JSON.parse(solc.compile(JSON.stringify(input)))
  for (const err of output.errors ?? []) {
    if (err.severity === 'error') {
      console.error(err.formattedMessage)
      process.exitCode = 1
    } else {
      console.warn(err.formattedMessage)
    }
  }
  if (process.exitCode) process.exit(process.exitCode)
  return output.contracts[name][name.replace('.sol', '')]
}

function artifact(name, contract, ast) {
  return {
    contractName: name,
    abi: contract.abi,
    bytecode: '0x' + contract.evm.bytecode.object,
    deployedBytecode: '0x' + contract.evm.deployedBytecode.object,
    immutableReferences: contract.evm.deployedBytecode.immutableReferences ?? {},
    // the ast carries the immutable name → AST id mapping (patchImmutablesMulti)
    ast,
  }
}

function emitAbi(path, constName, comment, abi) {
  writeFileSync(path, comment + `\n\nexport const ${constName} = ` + JSON.stringify(abi, null, 2) + ' as const\n')
}

const TARGETS = [
  {
    source: 'FileRegistryV2.sol',
    out: 'FileRegistryV2.json',
    abi: ['frontend/src/lib/registry-abi.ts', 'REGISTRY_ABI', '// Generated by scripts/p3/compile.mjs (contracts/FileRegistryV2.sol) — do not edit'],
  },
  {
    source: 'FileRegistry.sol',
    out: 'FileRegistry.json',
    abi: [
      'frontend/src/lib/registry-abi-v1.ts',
      'REGISTRY_V1_ABI',
      '// Generated by scripts/p3/compile.mjs (contracts/FileRegistry.sol, frozen v1) — do not edit.\n// Only for reading the old v1 registry (its Entry has no feePaid) and the v1→v2 migration',
    ],
  },
  {
    source: 'Mailbox.sol',
    out: 'Mailbox.json',
    abi: ['frontend/src/lib/mailbox-abi.ts', 'MAILBOX_ABI', '// Generated by scripts/p3/compile.mjs (contracts/Mailbox.sol) — do not edit'],
  },
  // Paywall.sol / PaywallV2.sol still compile into contracts/out (acceptance
  // tooling uses them), but since 2026-10-31 no frontend ABI is emitted — the
  // paid-download frontend was removed entirely
  {
    source: 'DirectSales.sol',
    out: 'DirectSales.json',
    abi: ['frontend/src/lib/sales-abi.ts', 'DIRECT_SALES_ABI', '// Generated by scripts/p3/compile.mjs (contracts/DirectSales.sol, direct-sales contract) — do not edit'],
  },
]

mkdirSync(OUT, { recursive: true })
for (const t of TARGETS) {
  if (!existsSync(ROOT + 'contracts/' + t.source)) {
    console.warn(`skip ${t.source} (missing)`)
    continue
  }
  const contract = compile(t.source)
  const ast = JSON.parse(solc.compile(JSON.stringify({
    language: 'Solidity',
    sources: { [t.source]: { content: readFileSync(ROOT + 'contracts/' + t.source, 'utf8') } },
    settings: { outputSelection: { '*': { '': ['ast'] } } },
  }))).sources[t.source].ast
  const art = artifact(t.source.replace('.sol', ''), contract, ast)
  writeFileSync(OUT + t.out, JSON.stringify(art, null, 2))
  const [abiPath, abiName, abiComment] = t.abi
  emitAbi(ROOT + abiPath, abiName, abiComment, contract.abi)
  console.log(`${t.source}: bytecode ${(art.bytecode.length / 2 / 1024).toFixed(2)} KiB → contracts/out/${t.out} · abi (${contract.abi.length} items) → ${abiPath}`)
}
