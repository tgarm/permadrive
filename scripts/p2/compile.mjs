// Compile FileRegistry.sol (solc-js, optimizer 200 / evmVersion paris — no
// reliance on newer EVM opcodes, safe on any frontier domain). Outputs:
//   contracts/out/FileRegistry.json          full artifact (bytecode + abi)
//   frontend/src/lib/registry-abi.ts         ABI only (TS const, bundled by the frontend)
// Usage: npm run compile

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import solc from 'solc'

const SOL = new URL('../../contracts/FileRegistry.sol', import.meta.url).pathname
const OUT = new URL('../../contracts/out/', import.meta.url).pathname
const ABI_OUT = new URL('../../frontend/src/lib/registry-abi.ts', import.meta.url).pathname

const input = {
  language: 'Solidity',
  sources: { 'FileRegistry.sol': { content: readFileSync(SOL, 'utf8') } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: 'paris',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'] } },
  },
}

const output = JSON.parse(solc.compile(JSON.stringify(input)))
for (const err of output.errors ?? []) {
  if (err.severity === 'error') {
    console.error(err.formattedMessage)
    process.exitCode = 1
  } else {
    console.warn(err.formattedMessage)
  }
}
if (process.exitCode) process.exit(process.exitCode)

const contract = output.contracts['FileRegistry.sol'].FileRegistry
mkdirSync(OUT, { recursive: true })
writeFileSync(
  OUT + 'FileRegistry.json',
  JSON.stringify(
    {
      contractName: 'FileRegistry',
      abi: contract.abi,
      bytecode: '0x' + contract.evm.bytecode.object,
      deployedBytecode: '0x' + contract.evm.deployedBytecode.object,
    },
    null,
    2,
  ),
)
writeFileSync(ABI_OUT, '// Generated by scripts/p2/compile.mjs (contracts/FileRegistry.sol) — do not edit by hand\n\nexport const REGISTRY_ABI = ' + JSON.stringify(contract.abi, null, 2) + ' as const\n')
console.log(`bytecode ${(contract.evm.bytecode.object.length / 2 / 1024).toFixed(2)} KiB → ${OUT}FileRegistry.json`)
console.log(`abi (${contract.abi.length} items) → ${ABI_OUT}`)
